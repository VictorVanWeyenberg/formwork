use crate::error::SchematicError;
use crate::visitor::{ConfirmAll, UnmakeAll, VisitorFlow};

/// Internal plumbing: status and continuation signal for a single level in depth-limited BFS traversal.
///
/// # Warning
/// This is an **internal plumbing** type used internally by [`Schematic::walk_choices`].
/// Application code and end users should never interact with `Level` directly.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Level {
    /// The control flow decision (`Continue` or `Break`) produced by visiting choices.
    pub flow: VisitorFlow,
    /// Indicates whether deeper child levels exist in the schematic hierarchy.
    pub deeper: bool,
}

impl Level {
    /// Creates a level continuation signal indicating whether deeper nodes exist.
    pub fn continue_level(deeper: bool) -> Self {
        Self {
            flow: VisitorFlow::Continue,
            deeper,
        }
    }

    /// Creates a level break signal halting further traversal.
    pub fn break_level() -> Self {
        Self {
            flow: VisitorFlow::Break,
            deeper: false,
        }
    }

    /// Creates a level signal from a [`VisitorFlow`] without deeper nodes.
    pub fn from_flow(flow: VisitorFlow) -> Self {
        Self {
            flow,
            deeper: false,
        }
    }

    /// Combines this level signal with another level signal.
    pub fn combine(&mut self, other: Level) {
        if other.flow == VisitorFlow::Break {
            self.flow = VisitorFlow::Break;
        }
        if other.deeper {
            self.deeper = true;
        }
    }
}

/// Result returned by [`SchematicSession::step`] representing the outcome of a single traversal step.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum StepResult {
    /// A choice was visited. Contains the flow signal returned by the visitor.
    Choice(VisitorFlow),
    /// All choices in the schematic tree have been confirmed or traversed.
    Complete,
    /// [`VisitorFlow::Back`] was returned at Choice 0; no choices were modified.
    AtStart,
}

impl StepResult {
    /// Returns `true` if this result is [`StepResult::Choice`].
    pub fn is_choice(&self) -> bool {
        matches!(self, Self::Choice(_))
    }

    /// Returns `true` if this result is [`StepResult::Complete`].
    pub fn is_complete(&self) -> bool {
        matches!(self, Self::Complete)
    }

    /// Returns `true` if this result is [`StepResult::AtStart`].
    pub fn is_at_start(&self) -> bool {
        matches!(self, Self::AtStart)
    }
}

/// Internal plumbing: outcome of stepping through a single choice at a target index.
///
/// # Warning
/// This is an **internal plumbing** type used internally by [`Walkable`].
/// Application code should interact with [`StepResult`] instead.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum StepOutcome {
    /// A choice matching the target index was visited with the given flow signal.
    Visited(VisitorFlow),
    /// No choice was found at the target index (all choices exhausted).
    Exhausted,
}

/// Internal plumbing: helper trait implemented by macro-generated structs to support traversal.
///
/// # Warning
/// This is an **internal plumbing** trait implemented by code generated by `#[schematic]`.
/// Application code should not invoke or implement `Walkable` directly.
/// Instead, call [`Schematic::walk_choices`] or [`Schematic::session`] to traverse choices across the hierarchy.
pub trait Walkable<V> {
    /// Steps traversal by visiting the choice at `target` index.
    fn walk_step(&mut self, visitor: &mut V, target: usize, current: &mut usize) -> StepOutcome;

    /// Unmakes the choice at `target` index into [`ChoiceState::UnmadeWithHistory`](crate::choice::ChoiceState::UnmadeWithHistory).
    fn unmake_at_index(&mut self, target: usize, current: &mut usize) -> bool;

    /// Internal plumbing: steps traversal at a specific depth level (for BFS traversal).
    #[doc(hidden)]
    fn walk_step_level(
        &mut self,
        visitor: &mut V,
        depth: usize,
        target: usize,
        current: &mut usize,
    ) -> (StepOutcome, bool) {
        if depth == 0 {
            (self.walk_step(visitor, target, current), false)
        } else {
            (StepOutcome::Exhausted, false)
        }
    }

    /// Internal plumbing: unmakes the choice at `target` index at a specific depth level (for BFS traversal).
    #[doc(hidden)]
    fn unmake_step_level(
        &mut self,
        depth: usize,
        target: usize,
        current: &mut usize,
    ) -> (bool, bool) {
        if depth == 0 {
            (self.unmake_at_index(target, current), false)
        } else {
            (false, false)
        }
    }
}

/// An interactive stepping session to drive choice traversal caller-by-caller.
pub struct SchematicSession<'a, S> {
    schematic: &'a mut S,
    cursor: usize,
    history: Vec<usize>,
}

impl<'a, S> SchematicSession<'a, S> {
    /// Creates a new interactive session for the given schematic.
    pub fn new(schematic: &'a mut S) -> Self {
        Self {
            schematic,
            cursor: 0,
            history: Vec::new(),
        }
    }

    /// Visits the next choice in traversal order.
    pub fn step<V>(&mut self, visitor: &mut V) -> StepResult
    where
        S: Walkable<V>,
    {
        let mut current = 0;
        let outcome = self.schematic.walk_step(visitor, self.cursor, &mut current);
        match outcome {
            StepOutcome::Visited(flow) => match flow {
                VisitorFlow::Continue => {
                    self.history.push(self.cursor);
                    self.cursor += 1;
                    StepResult::Choice(VisitorFlow::Continue)
                }
                VisitorFlow::Break => StepResult::Choice(VisitorFlow::Break),
                VisitorFlow::Back => {
                    if let Some(prev) = self.history.pop() {
                        let mut current_unmake = 0;
                        Walkable::<V>::unmake_at_index(self.schematic, prev, &mut current_unmake);
                        self.cursor = prev;
                        StepResult::Choice(VisitorFlow::Back)
                    } else {
                        StepResult::AtStart
                    }
                }
            },
            StepOutcome::Exhausted => StepResult::Complete,
        }
    }

    /// Returns the current step index (0-based).
    pub fn current_step(&self) -> usize {
        self.cursor
    }

    /// Returns an immutable reference to the underlying schematic.
    pub fn schematic(&self) -> &S {
        self.schematic
    }

    /// Returns a mutable reference to the underlying schematic.
    pub fn schematic_mut(&mut self) -> &mut S {
        self.schematic
    }

    /// Returns true if all choices in the schematic are complete.
    pub fn is_complete(&self) -> bool
    where
        S: Schematic,
    {
        self.schematic.is_complete()
    }
}

/// Primary trait implemented by unresolved representations (`<Name>Schematic`) of schematic types.
///
/// `Schematic` provides lifecycle operations for blueprints: checking completeness,
/// resolving into watertight domain models, and traversing or mutating choices.
pub trait Schematic: Sized {
    /// The final, watertight domain type produced when all choices are resolved.
    type Resolved;

    /// Checks if all choices in this schematic and all nested child schematics are currently made.
    ///
    /// Returns `true` if and only if every slot is satisfied (either fixed or with choices confirmed).
    fn is_complete(&self) -> bool;

    /// Consumes the unresolved blueprint and converts it into its watertight domain model [`Resolved`](Self::Resolved).
    ///
    /// # Errors
    /// Returns [`SchematicError::UnresolvedChoice`]
    /// if any choices remain pending or unmade.
    fn resolve(self) -> Result<Self::Resolved, SchematicError>;

    /// Creates an interactive stepping session to drive choices one-by-one.
    fn session(&mut self) -> SchematicSession<'_, Self> {
        SchematicSession::new(self)
    }

    /// Traverses choices in the schematic hierarchy, invoking `visitor` on each choice.
    ///
    /// Driven by [`SchematicSession::step`], supporting forward traversal, early breaks, and rewinding.
    fn walk_choices<V>(&mut self, visitor: &mut V) -> VisitorFlow
    where
        Self: Walkable<V>,
    {
        let mut session = self.session();
        loop {
            match session.step(visitor) {
                StepResult::Choice(VisitorFlow::Continue) => continue,
                StepResult::Choice(VisitorFlow::Break) => return VisitorFlow::Break,
                StepResult::Choice(VisitorFlow::Back) => continue,
                StepResult::AtStart => return VisitorFlow::Back,
                StepResult::Complete => return VisitorFlow::Continue,
            }
        }
    }

    /// Reverts all made choices in the schematic hierarchy back to pending, while preserving
    /// the selection history so they can be re-confirmed later via [`confirm_all`](Self::confirm_all).
    fn unmake_all(&mut self)
    where
        Self: Walkable<UnmakeAll>,
    {
        let mut unmaker = UnmakeAll;
        self.walk_choices(&mut unmaker);
    }

    /// Re-confirms all unmade choices in the schematic hierarchy that possess a valid selection history.
    fn confirm_all(&mut self)
    where
        Self: Walkable<ConfirmAll>,
    {
        let mut confirmer = ConfirmAll;
        self.walk_choices(&mut confirmer);
    }
}
